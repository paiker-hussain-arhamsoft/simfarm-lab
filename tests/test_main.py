class TestListLevels:
    def test_returns_three_levels(self, client):
        resp = client.get("/api/levels")
        assert resp.status_code == 200
        levels = resp.json()["levels"]
        assert len(levels) == 3
        ids = [l["id"] for l in levels]
        assert ids == ["beginner", "easy", "legendary"]



class TestPhishingGameEndpoints:
    def test_new_game(self, client):
        resp = client.post("/api/phishing/new-game")
        assert resp.status_code == 200
        data = resp.json()
        assert "session_id" in data
        assert "company_directory" in data

    def test_directory(self, client):
        resp = client.get("/api/phishing/directory")
        assert resp.status_code == 200
        assert len(resp.json()["directory"]) == 5

    def test_send_and_status(self, client):
        game = client.post("/api/phishing/new-game").json()
        sid = game["session_id"]

        resp = client.post("/api/phishing/send", json={
            "session_id": sid,
            "target_email": "j.park@novacomdigital.com",
            "subject": "Quick question",
            "body": "Hi James, I have a question about your project.",
            "sender_alias": "Recruiter",
            "pretext": "mentorship",
        })
        assert resp.status_code == 200
        assert "game_status" in resp.json()

        status = client.get(f"/api/phishing/status/{sid}")
        assert status.status_code == 200
        assert status.json()["attempts_used"] == 1

    def test_send_unknown_session(self, client):
        resp = client.post("/api/phishing/send", json={
            "session_id": "nonexistent",
            "target_email": "j.park@novacomdigital.com",
            "subject": "S",
            "body": "B",
        })
        assert resp.status_code == 404

    def test_status_unknown_session(self, client):
        resp = client.get("/api/phishing/status/nonexistent")
        assert resp.status_code == 404

    def test_submit_report(self, client):
        game = client.post("/api/phishing/new-game").json()
        sid = game["session_id"]
        resp = client.post("/api/phishing/submit-report", json={
            "session_id": sid,
            "report_text": "Some report text",
        })
        assert resp.status_code == 200

    def test_submit_report_unknown_session(self, client):
        resp = client.post("/api/phishing/submit-report", json={
            "session_id": "nonexistent",
            "report_text": "text",
        })
        assert resp.status_code == 404


